    /** 表題と条項（見出し・本文の組）から同意事項の PDF を作る。 */
    public static byte[] render(String title, String versionLabel, String[][] articles) {
        PdfDocumentBuilder b = new PdfDocumentBuilder(title, "（サンプル）" + title + "　" + versionLabel);
        b.title("（サンプル）" + title);
        b.note(versionLabel + "　この文書はサンプルです。実際の同意事項の PDF に差し替えてください。");
        b.space(6);
        for (String[] a : articles) {
            b.heading(a[0]);
            b.text(a[1], 9.5f);
        }
        return b.toBytes();
    }

