-- 4.1 会社区分マスタ
CREATE TABLE M_COMPANY_DIV (
    COMPANY_DIV        CHAR(1)        NOT NULL,
    COMPANY_DIV_NAME   NVARCHAR(50)   NOT NULL,
    PRE_CHECK_FLG      CHAR(1)        NOT NULL,
    AMOUNT_RATIO_LIMIT DECIMAL(3,2)   NOT NULL,
    CREATED_AT         DATETIME2(3)   NOT NULL,
    CREATED_BY         NVARCHAR(20)   NOT NULL,
    UPDATED_AT         DATETIME2(3)   NOT NULL,
    UPDATED_BY         NVARCHAR(20)   NOT NULL,
    ROW_VERSION        INT            NOT NULL DEFAULT 1,
    CONSTRAINT PK_M_COMPANY_DIV PRIMARY KEY (COMPANY_DIV)
);

-- 4.2 社員マスタ
CREATE TABLE M_EMPLOYEE (
    EMPLOYEE_ID    BIGINT IDENTITY(1,1) NOT NULL,
    EMPLOYEE_NO    NVARCHAR(10)   NOT NULL,
    EMPLOYEE_NAME  NVARCHAR(50)   NOT NULL,
    PASSWORD_HASH  NVARCHAR(100)  NOT NULL,
    COMPANY_DIV    CHAR(1)        NOT NULL,
    DEPT_CD        NVARCHAR(10)   NOT NULL,
    ROLE_CD        CHAR(2)        NOT NULL,
    MAIL_ADDRESS   NVARCHAR(254)  NOT NULL,
    VALID_FLG      CHAR(1)        NOT NULL,
    CREATED_AT     DATETIME2(3)   NOT NULL,
    CREATED_BY     NVARCHAR(20)   NOT NULL,
    UPDATED_AT     DATETIME2(3)   NOT NULL,
    UPDATED_BY     NVARCHAR(20)   NOT NULL,
    ROW_VERSION    INT            NOT NULL DEFAULT 1,
    CONSTRAINT PK_M_EMPLOYEE PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT UK_M_EMPLOYEE_01 UNIQUE (EMPLOYEE_NO),
    CONSTRAINT FK_M_EMPLOYEE_COMPANY_DIV FOREIGN KEY (COMPANY_DIV) REFERENCES M_COMPANY_DIV (COMPANY_DIV)
);
CREATE INDEX IX_M_EMPLOYEE_01 ON M_EMPLOYEE (COMPANY_DIV, DEPT_CD);

-- 4.3 申込者マスタ
CREATE TABLE M_APPLICANT (
