-- 4.5 ステータス遷移マスタ
CREATE TABLE M_STATUS_TRANSITION (
    TRANSITION_ID  INT            NOT NULL,
    FROM_STATUS_CD CHAR(5)        NOT NULL,
    ACTION_CD      CHAR(2)        NOT NULL,
    CONDITION_CD   CHAR(2)        NOT NULL,
    EVAL_ORDER     INT            NOT NULL,
    TO_STATUS_CD   CHAR(5)        NOT NULL,
    ACTOR_TYPE     CHAR(1)        NOT NULL,
    PRE_CHECK_COND CHAR(1)        NOT NULL,
    REF_NO         NVARCHAR(20)   NULL,
    CREATED_AT     DATETIME2(3)   NOT NULL,
    CREATED_BY     NVARCHAR(20)   NOT NULL,
    UPDATED_AT     DATETIME2(3)   NOT NULL,
    UPDATED_BY     NVARCHAR(20)   NOT NULL,
    ROW_VERSION    INT            NOT NULL DEFAULT 1,
    CONSTRAINT PK_M_STATUS_TRANSITION PRIMARY KEY (TRANSITION_ID),
    CONSTRAINT UK_M_STATUS_TRANSITION_01 UNIQUE (FROM_STATUS_CD, ACTION_CD, PRE_CHECK_COND, EVAL_ORDER),
    CONSTRAINT FK_M_STATUS_TRANSITION_FROM FOREIGN KEY (FROM_STATUS_CD) REFERENCES M_STATUS (STATUS_CD),
    CONSTRAINT FK_M_STATUS_TRANSITION_TO FOREIGN KEY (TO_STATUS_CD) REFERENCES M_STATUS (STATUS_CD)
);

