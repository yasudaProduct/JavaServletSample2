-- 4.10 申込
CREATE TABLE T_APPLICATION (
    APPLICATION_ID        BIGINT IDENTITY(1,1) NOT NULL,
    APPLICATION_NO        NVARCHAR(12)   NOT NULL,
    APPLICANT_ID          BIGINT         NOT NULL,
    OWNER_EMPLOYEE_ID     BIGINT         NOT NULL,
    COMPANY_DIV           CHAR(1)        NOT NULL,
    DEPT_CD               NVARCHAR(10)   NOT NULL,
    STATUS_CD             CHAR(5)        NOT NULL,
    CURRENT_VERSION_NO    INT            NOT NULL,
    BASE_VERSION_NO       INT            NULL,
    REVIEWED_VERSION_NO   INT            NULL,
    REGISTRATION_TYPE     CHAR(1)        NOT NULL,
    SOURCE_APPLICATION_ID BIGINT         NULL,
    IMPORT_BATCH_ID       BIGINT         NULL,
    REVIEWED_AT           DATETIME2(3)   NULL,
    CREATED_AT            DATETIME2(3)   NOT NULL,
    CREATED_BY            NVARCHAR(20)   NOT NULL,
    UPDATED_AT            DATETIME2(3)   NOT NULL,
    UPDATED_BY            NVARCHAR(20)   NOT NULL,
    ROW_VERSION           INT            NOT NULL DEFAULT 1,
    CONSTRAINT PK_T_APPLICATION PRIMARY KEY (APPLICATION_ID),
    CONSTRAINT UK_T_APPLICATION_01 UNIQUE (APPLICATION_NO),
    CONSTRAINT FK_T_APPLICATION_APPLICANT FOREIGN KEY (APPLICANT_ID) REFERENCES M_APPLICANT (APPLICANT_ID),
    CONSTRAINT FK_T_APPLICATION_OWNER FOREIGN KEY (OWNER_EMPLOYEE_ID) REFERENCES M_EMPLOYEE (EMPLOYEE_ID),
    CONSTRAINT FK_T_APPLICATION_COMPANY_DIV FOREIGN KEY (COMPANY_DIV) REFERENCES M_COMPANY_DIV (COMPANY_DIV),
    CONSTRAINT FK_T_APPLICATION_STATUS FOREIGN KEY (STATUS_CD) REFERENCES M_STATUS (STATUS_CD),
    CONSTRAINT FK_T_APPLICATION_SOURCE FOREIGN KEY (SOURCE_APPLICATION_ID) REFERENCES T_APPLICATION (APPLICATION_ID),
    CONSTRAINT FK_T_APPLICATION_IMPORT FOREIGN KEY (IMPORT_BATCH_ID) REFERENCES T_IMPORT_BATCH (IMPORT_BATCH_ID)
);
CREATE INDEX IX_T_APPLICATION_01 ON T_APPLICATION (STATUS_CD);
CREATE INDEX IX_T_APPLICATION_02 ON T_APPLICATION (OWNER_EMPLOYEE_ID, STATUS_CD);
CREATE INDEX IX_T_APPLICATION_03 ON T_APPLICATION (APPLICANT_ID);

