    UPDATED_BY     NVARCHAR(20)   NOT NULL,
    ROW_VERSION    INT            NOT NULL DEFAULT 1,
    CONSTRAINT PK_M_APPLICANT PRIMARY KEY (APPLICANT_ID),
    CONSTRAINT UK_M_APPLICANT_01 UNIQUE (APPLICANT_NO)
);

-- 4.4 ステータスマスタ
CREATE TABLE M_STATUS (
    STATUS_CD             CHAR(5)        NOT NULL,
